#![cfg(feature = "oracle")]
use zsyn::Mode;
use zsyn_comparison::equivalence;

#[test]
fn lexical_boundaries_and_utf8_modes_match() {
    let markup = [
        "ordinary words",
        "word-other",
        "x_y",
        "foo*bar",
        "word-other x_y foo*bar",
        "a\u{00a0}b\u{2003}c\u{000b}\u{000c}",
        "one  two",
        "one\ttwo",
        "a\nb",
        "a\r\nb",
        "a\rb",
        "a\u{85}b",
        "a\u{2028}b",
        "a\u{2029}b",
        "a\n \nb",
        "a\r\n\r\nb",
        "中文 标题",
        "café λ",
        "e\u{301}",
        "🦀 🐍",
        "👨‍👩‍👧‍👦",
        "🇨🇳",
        "a ",
        " a",
        " ",
        "\t",
        "\n",
        "\n\n",
        "\u{feff}text",
        "a\0b",
        "~",
        "--",
        "---",
        "-?",
        "...",
        "hello...",
        "'single'",
        "\"double\"",
        "\\#",
        "\\$",
        "\\*",
        "\\_",
        "\\\\",
        "\\u{41}",
        "\\u{1f980}",
        "\\u{0}",
        "\\u{d800}",
        "\\u{110000}",
        "\\u{zz}",
        "\\u{}",
        "\\u{41",
        "\\",
        "\\ ",
        "// line\ntext",
        "/* comment */",
        "/* a /* b */ c */",
        "/* unclosed",
        "*/",
        "`x`",
        "``",
        "```\nx\n```",
        "```lang\nx\n```",
        "`` ` ``",
        "`unclosed",
        "<a>",
        "<a-b_c:de.f>",
        "@a",
        "@a.b",
        "@a:sub",
        "@a!",
        "@a?",
        "@a,",
        "https://example.org",
        "http://example.org/a(b)",
        "https://example.org/a)",
        "https://example.org/a.",
        "= H",
        "== H",
        "- a",
        "+ a",
        "1. a",
        "22. a",
        "/ term: body",
        "*a*",
        "_a_",
        "*unfinished",
        "_unfinished",
        "$x$",
        "$x",
        "#x",
        "#x.",
        "#x.y",
        "#x-y",
    ];
    let code = [
        "0",
        "123",
        "0xff",
        "0xCAFE",
        "0b1010",
        "0o755",
        "1_000",
        "1.5",
        "1e3",
        "1e-3",
        "1e+3",
        "1.2e-3",
        "1pt",
        "1mm",
        "1cm",
        "1in",
        "1em",
        "1deg",
        "1rad",
        "1fr",
        "50%",
        "1.5pt",
        "1e2pt",
        "0x",
        "0b2",
        "0o9",
        "1e",
        "1foo",
        "1e999",
        "9223372036854775808",
        "\"\"",
        "\"text\"",
        "\"中文 🦀\"",
        "\"a\\n\\t\\r\\\\\\\"\"",
        "\"\\u{1f980}\"",
        "\"\\q\"",
        "\"\\u{zz}\"",
        "\"unterminated",
        "none",
        "auto",
        "true",
        "false",
        "_x",
        "x-y",
        "中文",
        "café",
        "a\u{301}",
        "π",
        "_",
        "self",
        "// c\n1",
        "/* c */ 1",
        "/* unclosed",
        "`code`",
        "$x^2$",
        "[hello]",
        "<label>",
    ];
    let math = [
        "x",
        "xy",
        "alpha",
        "pi",
        "α",
        "π",
        "中文",
        "🦀",
        "e\u{301}",
        "👨‍👩‍👧‍👦",
        "🇨🇳",
        "123",
        "1.25",
        ".5",
        "x_1",
        "x^2",
        "x_1^2",
        "x'",
        "x'''",
        "x!",
        "x!!",
        "x/y",
        "x / y",
        "√x",
        "∛x",
        "∜x",
        "->",
        "<->",
        "=>",
        "<=>",
        "<=",
        ">=",
        "!=",
        ":=",
        "::=",
        "...",
        "&",
        "\\",
        "\\#",
        "\\u{1f980}",
        "arrow.r.long",
        "sin(x)",
        "frac(a, b)",
        "\"text\"",
        "#x",
        "#(1 + 2)",
        "/* c */x",
        "(x)",
        "[x]",
        "{x}",
        "|x|",
    ];
    let mut failures = Vec::new();
    for (mode, inputs) in [
        (Mode::Markup, &markup[..]),
        (Mode::Code, &code[..]),
        (Mode::Math, &math[..]),
    ] {
        for source in inputs {
            if let Err(error) = equivalence(source, mode) {
                failures.push(format!("{mode:?} {source:?}: {error}"));
            }
        }
    }
    assert!(
        failures.is_empty(),
        "{} lexical cases failed:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
